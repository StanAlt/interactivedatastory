// Model: national margin implied by the 2024-vote groups (share-weighted).
export function impliedMargin(groups) {
  return groups
    .filter((g) => g.d != null && g.r != null)
    .reduce((a, g) => a + (g.share * (g.d - g.r)) / 100, 0);
}

