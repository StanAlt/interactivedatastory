/* ── Helpers ── */

export const round1 = (v) => Math.round(v * 10) / 10;

export function marginLabel(m) {
  if (m == null) return "n/a";
  const v = round1(m);
  if (v === 0) return "Even";
  return v > 0 ? `D+${Math.abs(v)}` : `R+${Math.abs(v)}`;
}

export function shiftLabel(s) {
  if (s == null) return "n/a";
  const v = round1(s);
  if (v === 0) return "No change";
  return `${Math.abs(v)} pts toward ${v > 0 ? "D" : "R"}`;
}

