function race(st, name, challenger, republican, opts) {
  const [cName, cParty, cPct] = challenger;
  const [rName, rPct] = republican;
  const m26 = opts.margin != null ? opts.margin : round1(cPct - rPct);
  const comparable = cParty === "D";
  return {
    st,
    name,
    cands: [
      { name: cName, party: cParty, pct: cPct },
      { name: rName, party: "R", pct: rPct },
    ].sort((a, b) => (b.pct ?? 0) - (a.pct ?? 0)),
    winner: opts.winner,
    called: opts.called !== false,
    flip: !!opts.flip,
    from: opts.flip ? "R" : null,
    pres24: opts.pres24,
    m26,
    comparable,
    shift: comparable ? round1(m26 - opts.pres24) : null,
    count: opts.count || null,
    note: opts.note || null,
    sources: [...opts.sources, opts.presSource || "pres-2024"],
  };
}

